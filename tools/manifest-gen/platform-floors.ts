// Apple floors as `package.yml` and `app.yml` spell them, keyed to the
// `wuhu_platform_floor` attribute and the rc lines that set the minimum of the
// platform's lanes. macOS sets it for every build, not only `--config=mac`:
// a bare build on a Mac (`deno task test`, DocC, a direct `bazel test`) is the
// mac lane. visionOS has no `--visionos_minimum_os`: apple_support reads the
// generic `--minimum_os_version` for it.
const platformFloors = {
  macOS: {
    attr: 'macos',
    scopes: ['common', 'common:mac'],
    flag: '--macos_minimum_os',
  },
  iOS: {
    attr: 'ios',
    scopes: ['common:ios', 'common:ios-device'],
    flag: '--ios_minimum_os',
  },
  tvOS: {
    attr: 'tvos',
    scopes: ['common:tvos', 'common:tvos-device'],
    flag: '--tvos_minimum_os',
  },
  visionOS: {
    attr: 'visionos',
    scopes: ['common:visionos', 'common:visionos-device'],
    flag: '--minimum_os_version',
  },
  watchOS: {
    attr: 'watchos',
    scopes: ['common:watchos', 'common:watchos-device'],
    flag: '--watchos_minimum_os',
  },
} as const

type FloorPlatform = keyof typeof platformFloors

export type Floors = Readonly<Record<string, string>>

export const laneFloorsBazelrc = 'bazel/lane-floors.bazelrc'

export function comparePlatformVersions(lhs: string, rhs: string): number {
  const parse = (version: string) =>
    version.split('.').map((part) => Number.parseInt(part, 10))
  const left = parse(lhs)
  const right = parse(rhs)
  if (left.some(Number.isNaN) || right.some(Number.isNaN)) {
    throw new Error(`unparsable platform version: ${lhs} vs ${rhs}`)
  }
  for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
    const diff = (left[index] ?? 0) - (right[index] ?? 0)
    if (diff !== 0) return diff
  }
  return 0
}

function floorPlatforms(floors: Floors, location: string): FloorPlatform[] {
  const unknown = Object.keys(floors).filter((platform) =>
    !(platform in platformFloors)
  )
  if (unknown.length > 0) {
    throw new Error(
      `${location} declares unknown platforms: ${unknown.join(', ')}`,
    )
  }
  return (Object.keys(platformFloors) as FloorPlatform[]).filter((platform) =>
    floors[platform] !== undefined
  )
}

export function platformFloorRule(
  name: string,
  floors: Floors,
  location: string,
  extraAttrs = '',
): string {
  const attrs = floorPlatforms(floors, location).map((platform) =>
    `    ${platformFloors[platform].attr} = "${floors[platform]}",\n`
  ).join('')
  return `wuhu_platform_floor(\n    name = "${name}",\n${attrs}${extraAttrs})\n`
}

// The lowest of every floor seen per platform. A check lane compiles at this
// minimum and each package raises its own code to its floor, so nothing in the
// graph is compiled above the floor of an importer.
export function lowestFloors(
  declarations: readonly { floors: Floors; location: string }[],
): Map<FloorPlatform, string> {
  const result = new Map<FloorPlatform, string>()
  for (const { floors, location } of declarations) {
    for (const platform of floorPlatforms(floors, location)) {
      const existing = result.get(platform)
      if (
        existing === undefined ||
        comparePlatformVersions(floors[platform], existing) < 0
      ) {
        result.set(platform, floors[platform])
      }
    }
  }
  return result
}

export function laneFloorsBazelrcContent(
  floors: ReadonlyMap<FloorPlatform, string>,
): string {
  const lines = (Object.keys(platformFloors) as FloorPlatform[])
    .filter((platform) => floors.has(platform))
    .flatMap((platform) => {
      const { scopes, flag } = platformFloors[platform]
      return scopes.map((scope) => `${scope} ${flag}=${floors.get(platform)}`)
    })
  return `# Generated by deno task generate-manifests from the lowest package and app\n# floor per platform. Do not edit; docs/bazel.md, "Platform floors".\n${
    lines.join('\n')
  }\n`
}

// A package, or an app bundle at its minimum, and the package directories it
// imports from.
export interface FloorEdge {
  location: string
  floors: Floors
  dependsOn: readonly string[]
}

// Each package compiles at its own floor, and swiftc refuses to import a module
// built for a newer OS than the importer. A dependency floored above its
// importer is that error waiting in some configuration; refusing it here also
// keeps every floor raise inside an app's configuration empty.
export function assertFloorEdges(
  packageFloors: ReadonlyMap<string, Floors>,
  edges: readonly FloorEdge[],
): void {
  const violations = new Set<string>()
  for (const { location, floors, dependsOn } of edges) {
    for (const dir of dependsOn) {
      const dependency = packageFloors.get(dir)
      if (dependency === undefined) continue
      for (const platform of floorPlatforms(floors, location)) {
        const floor = dependency[platform]
        if (
          floor !== undefined &&
          comparePlatformVersions(floor, floors[platform]) > 0
        ) {
          violations.add(
            `${location} (${platform} ${
              floors[platform]
            }) imports ${dir} (${platform} ${floor})`,
          )
        }
      }
    }
  }
  if (violations.size > 0) {
    throw new Error(
      `A dependency's platform floor is above its importer's:\n  ${
        [...violations].join('\n  ')
      }\nLower the dependency's floor or raise the importer's (docs/bazel.md, "Platform floors").`,
    )
  }
}
